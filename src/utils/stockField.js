// تعديل المنتج: المخزون يُرسل فقط إن غيّره التاجر. المخزون قد يكون سالباً (طلبات مؤكدة فوق المتوفر)
// والخادم يرفض الرقم السالب؛ وإعادة إرسال الرقم القديم تمحو ما أنقصته الطلبات أثناء فتح الصفحة.
export function stockPatch(current, initial) {
  const n = Number(current) || 0;
  return n === (Number(initial) || 0) ? {} : { stock: n };
}
